// SourcePath is the repository-relative, hand-maintained SQL reference.
const SourcePath = "docs/reference/functions.sql"

// WriteFiles regenerates both reference views without executing example SQL.
// FILE/HTTP examples and ambient clocks must not affect generated documentation.
func WriteFiles(root string) error {
	source, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(SourcePath)))
	if err != nil {
		return err
	}
	sections, err := Generate(bytes.NewReader(source))
	if err != nil {
		return err
	}
	var json, html bytes.Buffer
	if err := Encode(&json, sections); err != nil {
		return err
	}
	if err := RenderHTML(&html, source); err != nil {
		return err
	}
	for path, data := range map[string][]byte{
		"cmd/wasm_browser/web/function_examples.json": json.Bytes(),
		"docs/reference/functions.html":               html.Bytes(),
	} {
		path = filepath.Join(root, filepath.FromSlash(path))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, data, 0o644); err != nil {
			return fmt.Errorf("write reference: %w", err)
		}
	}
	return nil
}

// RenderHTML retains explanatory comments and escapes all SQL as text.
func RenderHTML(w io.Writer, source []byte) error {
	sections, err := generate(bytes.NewReader(source), true)
	if err != nil {
		return err
	}
	return referenceHTML.Execute(w, sections)
}

